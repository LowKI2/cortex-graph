let dict = null;
export function t(key, ...args) {
  if (!dict) {
    let lang = 'en';
    try { lang = String(moment.locale() || 'en'); } catch { /* ignore */ }
    dict = lang.startsWith('de') ? DE : EN;
  }
  const v = dict[key] ?? EN[key] ?? key;
  return typeof v === 'function' ? v(...args) : v;
}
